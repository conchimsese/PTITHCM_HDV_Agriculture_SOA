#!/usr/bin/env python3
"""Synchronize project AI instructions across Antigravity, Codex, and Claude Code.

Source of truth:
  - .agents/rules/*.md  (requires YAML frontmatter starting with `trigger:`)
  - AGENTS.md           (project playbook containing SYNC:RULES markers)
  - MAP.md              (architecture and command map)

Targets updated:
  - AGENTS.md           (refreshes auto-managed rules table & always_on rules)
  - CLAUDE.md           (generated entrypoint for Claude Code)
  - .claude/rules/*.md  (1:1 rule sync with Claude Code `paths:` frontmatter)

Usage:
  python scripts/sync-ai-config.py
  python scripts/sync-ai-config.py --check
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

VALID_TRIGGERS = {"always_on", "glob", "model_decision", "manual"}
SYNC_START = "<!-- SYNC:RULES:START -->"
SYNC_END = "<!-- SYNC:RULES:END -->"
CLAUDE_BANNER = (
    "<!-- AUTO-GENERATED by scripts/sync-ai-config.py. "
    "Do NOT edit manually; edit AGENTS.md or .agents/rules/*.md and run `python scripts/sync-ai-config.py`. -->"
)


@dataclass(frozen=True)
class RuleFile:
    name: str
    rel_path: str
    trigger: str
    description: str
    globs: list[str]
    body: str


def split_frontmatter(text: str, file_path: Path) -> tuple[dict[str, object], str]:
    normalized = text.replace("\r\n", "\n")
    lines = normalized.split("\n")
    if not lines or lines[0].strip() != "---":
        raise ValueError(f"{file_path}: missing YAML frontmatter starting with '---' and 'trigger:'.")

    end_idx = None
    for idx in range(1, len(lines)):
        if lines[idx].strip() == "---":
            end_idx = idx
            break
    if end_idx is None:
        raise ValueError(f"{file_path}: unterminated YAML frontmatter (missing closing '---').")

    meta: dict[str, object] = {}
    current_list_key: str | None = None
    for raw_line in lines[1:end_idx]:
        stripped = raw_line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("- ") and current_list_key is not None:
            item = stripped[2:].strip().strip("'\"")
            existing = meta.setdefault(current_list_key, [])
            if isinstance(existing, list):
                existing.append(item)
            continue

        current_list_key = None
        if ":" not in raw_line:
            raise ValueError(f"{file_path}: invalid frontmatter line: {raw_line!r}")
        key, val = raw_line.split(":", 1)
        key = key.strip()
        val = val.strip()
        if not val:
            meta[key] = []
            current_list_key = key
        else:
            if val.startswith("[") and val.endswith("]"):
                inner = val[1:-1].strip()
                meta[key] = [
                    part.strip().strip("'\"") for part in inner.split(",") if part.strip()
                ]
            else:
                meta[key] = val.strip("'\"")

    body = "\n".join(lines[end_idx + 1 :]).lstrip("\n").rstrip() + "\n"
    return meta, body


def load_rules(root: Path) -> list[RuleFile]:
    rules_dir = root / ".agents" / "rules"
    if not rules_dir.is_dir():
        raise FileNotFoundError(f"Missing rules directory: {rules_dir}")

    rule_paths = sorted(p for p in rules_dir.glob("*.md") if p.is_file())
    if not rule_paths:
        raise ValueError(f"No rule markdown files found in {rules_dir}")

    parsed: list[RuleFile] = []
    for path in rule_paths:
        raw = path.read_text(encoding="utf-8")
        meta, body = split_frontmatter(raw, path)
        trigger = str(meta.get("trigger", "")).strip()
        if trigger not in VALID_TRIGGERS:
            raise ValueError(
                f"{path}: invalid or missing `trigger:` ({trigger!r}). "
                f"Expected one of {sorted(VALID_TRIGGERS)}."
            )

        raw_globs = meta.get("globs", [])
        if isinstance(raw_globs, str):
            globs = [g.strip() for g in raw_globs.split(",") if g.strip()]
        elif isinstance(raw_globs, list):
            globs = [str(g).strip() for g in raw_globs if str(g).strip()]
        else:
            globs = []

        if trigger == "glob" and not globs:
            raise ValueError(f"{path}: trigger 'glob' requires a non-empty `globs:` field.")

        description = str(meta.get("description", "")).strip()
        if not description:
            for line in body.splitlines():
                if line.startswith("# "):
                    description = line[2:].strip()
                    break
        parsed.append(
            RuleFile(
                name=path.name,
                rel_path=path.relative_to(root).as_posix(),
                trigger=trigger,
                description=description or path.stem,
                globs=globs,
                body=body,
            )
        )
    return parsed


def build_rules_block(rules: list[RuleFile], rule_link_prefix: str) -> str:
    lines: list[str] = [
        "| Rule | Trigger | Phạm vi / Mô tả |",
        "|---|---|---|",
    ]
    for rule in rules:
        scope = ", ".join(f"`{g}`" for g in rule.globs) if rule.globs else rule.description
        link = f"[{rule.name}]({rule_link_prefix}{rule.name})"
        lines.append(f"| {link} | `{rule.trigger}` | {scope} |")

    always_on = [r for r in rules if r.trigger == "always_on"]
    if always_on:
        lines.append("")
        lines.append("### Quy tắc luôn bật (`always_on`)")
        for rule in always_on:
            lines.append("")
            lines.append(f"<!-- source: {rule.rel_path} -->")
            lines.append(rule.body.rstrip())
    return "\n".join(lines).rstrip() + "\n"


def update_agents_md(agents_path: Path, rules: list[RuleFile]) -> str:
    if not agents_path.is_file():
        raise FileNotFoundError(f"Missing {agents_path}")
    content = agents_path.read_text(encoding="utf-8").replace("\r\n", "\n")
    block = f"{SYNC_START}\n{build_rules_block(rules, '.agents/rules/')}{SYNC_END}"

    pattern = re.compile(
        re.escape(SYNC_START) + r".*?" + re.escape(SYNC_END),
        flags=re.DOTALL,
    )
    if pattern.search(content):
        updated = pattern.sub(block, content, count=1)
    else:
        updated = content.rstrip() + "\n\n## 2. Quy tắc được đồng bộ tự động\n\n" + block + "\n"
    return updated.rstrip() + "\n"


def extract_agents_preamble(agents_content: str) -> str:
    idx = agents_content.find(SYNC_START)
    preamble = agents_content[:idx] if idx != -1 else agents_content
    # Remove heading immediately above SYNC_START if present
    preamble = re.sub(r"\n##\s+2\.\s+Quy tắc được đồng bộ tự động\s*\Z", "", preamble.rstrip())
    # Strip top `# AGENTS.md...` title so CLAUDE.md can use `# CLAUDE.md`
    preamble_lines = preamble.splitlines()
    if preamble_lines and preamble_lines[0].startswith("# "):
        preamble_lines = preamble_lines[1:]
    return "\n".join(preamble_lines).strip()


def build_claude_md(agents_updated: str, rules: list[RuleFile]) -> str:
    preamble = extract_agents_preamble(agents_updated)
    claude_rules_block = build_rules_block(rules, ".claude/rules/")
    parts = [
        CLAUDE_BANNER,
        "",
        "# CLAUDE.md — Hướng dẫn & Quy tắc Claude Code",
        "",
        preamble,
        "",
        "## 2. Quy tắc đã đồng bộ (`.claude/rules/`)",
        "",
        claude_rules_block.rstrip(),
        "",
    ]
    return "\n".join(parts)


def render_claude_rule(rule: RuleFile) -> str:
    header_lines: list[str] = []
    if rule.trigger == "glob" and rule.globs:
        header_lines.append("---")
        header_lines.append("paths:")
        for g in rule.globs:
            header_lines.append(f'  - "{g}"')
        header_lines.append("---")
        header_lines.append("")
    header_lines.append(
        f"<!-- Synced by scripts/sync-ai-config.py from {rule.rel_path} (trigger: {rule.trigger}). -->"
    )
    header_lines.append("")
    return "\n".join(header_lines) + rule.body.rstrip() + "\n"


def sync_all(root: Path, check_only: bool) -> int:
    rules = load_rules(root)
    agents_path = root / "AGENTS.md"
    claude_md_path = root / "CLAUDE.md"
    claude_rules_dir = root / ".claude" / "rules"

    desired_files: dict[Path, str] = {}
    agents_updated = update_agents_md(agents_path, rules)
    desired_files[agents_path] = agents_updated
    desired_files[claude_md_path] = build_claude_md(agents_updated, rules)

    expected_rule_paths: set[Path] = set()
    for rule in rules:
        target = claude_rules_dir / rule.name
        expected_rule_paths.add(target)
        desired_files[target] = render_claude_rule(rule)

    drifted: list[str] = []
    for path, expected in desired_files.items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.is_file() else None
        if current != expected:
            rel = path.relative_to(root).as_posix()
            drifted.append(rel)
            if not check_only:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding="utf-8", newline="\n")

    stale_files: list[Path] = []
    if claude_rules_dir.is_dir():
        for existing in sorted(claude_rules_dir.glob("*.md")):
            if existing not in expected_rule_paths:
                stale_files.append(existing)
                drifted.append(f"{existing.relative_to(root).as_posix()} (stale)")
                if not check_only:
                    existing.unlink()

    if check_only:
        if drifted:
            print("AI config is out of sync:", file=sys.stderr)
            for item in drifted:
                print(f"  - {item}", file=sys.stderr)
            print("Run: python scripts/sync-ai-config.py", file=sys.stderr)
            return 1
        print(
            f"OK: {len(rules)} rule(s) in sync across .agents/rules/, AGENTS.md, CLAUDE.md, and .claude/rules/."
        )
        return 0

    print(
        f"Synced {len(rules)} rule(s) -> AGENTS.md, CLAUDE.md, and .claude/rules/ "
        f"({len(drifted)} updated, {len(stale_files)} removed)."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify AGENTS.md, CLAUDE.md, and .claude/rules/ match .agents/rules/ without modifying files.",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    try:
        return sync_all(root, check_only=args.check)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
